// PRISM Investigation Report Exporter API Route
// Enforces server-side tenant isolation
const express = require('express');
const router = express.Router();
const { getDatabase } = require('../../db/database');
const { authenticate } = require('../../security/authMiddleware');
const { getScopedInvestigation } = require('../../security/tenantGuard');

// All report endpoints require authentication
router.use(authenticate);

// GET /api/v1/investigations/:id/report?format=markdown|json|html
router.get('/investigations/:id/report', (req, res) => {
  try {
    const { format = 'markdown' } = req.query;
    const inv = getScopedInvestigation(req.params.id, req.organization.id);
    if (!inv) {
      return res.status(404).json({ success: false, error: { code: 'NOT_FOUND', message: 'Investigation not found.' } });
    }

    const db = getDatabase();
    const evidence = db.prepare('SELECT * FROM evidence WHERE investigation_id = ?').all(inv.id);
    const hypotheses = db.prepare('SELECT * FROM hypotheses WHERE investigation_id = ?').all(inv.id);
    const rootCauses = db.prepare('SELECT * FROM root_causes WHERE investigation_id = ?').all(inv.id);
    const impact = db.prepare('SELECT * FROM impact_assessments WHERE investigation_id = ?').get(inv.id);
    const recommendations = db.prepare('SELECT * FROM recommendations WHERE investigation_id = ?').all(inv.id);
    const verifications = db.prepare(`
      SELECT v.*, h.statement as hypothesis_statement
      FROM verifications v
      JOIN experiments e ON v.experiment_id = e.id
      JOIN hypotheses h ON e.hypothesis_id = h.id
      WHERE h.investigation_id = ?
    `).all(inv.id);

    const reportData = {
      investigation: inv,
      evidence,
      hypotheses,
      verifications,
      rootCauses,
      impact,
      recommendations,
      exportedAt: new Date().toISOString()
    };

    if (format === 'json') {
      res.setHeader('Content-Type', 'application/json');
      res.setHeader('Content-Disposition', `attachment; filename="PRISM-REPORT-${inv.id}.json"`);
      return res.send(JSON.stringify(reportData, null, 2));
    }

    // Markdown format
    const mdLines = [
      `# PRISM Investigation Report: ${inv.title}`,
      `**Investigation ID**: \`${inv.id}\` | **Severity**: \`${inv.severity}\` | **Status**: \`${inv.status}\``,
      `**Started**: ${inv.started_at} | **Completed**: ${inv.completed_at || 'In Progress'}`,
      '',
      `## 1. Problem Statement`,
      `> ${inv.problem_statement}`,
      '',
      `## 2. Root Cause Analysis`,
      ...(rootCauses.length > 0
        ? rootCauses.map((rc, idx) => `### Root Cause ${idx + 1} (Confidence: ${(rc.confidence * 100).toFixed(0)}%)\n${rc.statement}\n- **Verification Reference**: \`${rc.verification_ref}\``)
        : ['*No definitive root cause established yet.*']),
      '',
      `## 3. Impact Assessment & Blast Radius`,
      impact ? [
        `- **Blast Radius Level**: ${impact.blast_radius_level}`,
        `- **Affected Components**: ${impact.affected_components}`,
        `- **User Impact**: ${impact.user_impact}`,
        `- **Data Integrity**: ${impact.data_integrity_impact}`,
        impact.financial_cost_estimate ? `- **Cost Estimate**: ${impact.financial_cost_estimate}` : ''
      ].filter(Boolean).join('\n') : '*No impact assessment recorded.*',
      '',
      `## 4. Verification Evidence & Experiments`,
      ...(verifications.length > 0 
        ? verifications.map(v => `- **[${v.outcome}]** ${v.claim}\n  *Method*: ${v.method}\n  *Actual Result*: ${v.actual_result}\n  *Limitations*: ${v.limitations || 'None'}`)
        : ['*No verification experiments completed.*']),
      '',
      `## 5. Normalized Evidence (${evidence.length} items)`,
      ...evidence.map(e => `- **[${e.type}]** ${e.title} (Source: \`${e.source}\`, Hash: \`${e.hash.substring(0, 12)}...\`)`),
      '',
      `## 6. Actionable Recommendations`,
      ...(recommendations.length > 0
        ? recommendations.map(r => `### [${r.priority}] ${r.action}\n- **Rationale**: ${r.rationale}\n- **Trade-offs**: ${r.tradeoffs}\n- **Risk**: ${r.risk}`)
        : ['*No recommendations filed yet.*']),
      '',
      `---`,
      `*Generated by PRISM Engineering Investigation Engine at ${reportData.exportedAt}*`
    ];

    const markdownContent = mdLines.join('\n');

    if (format === 'markdown') {
      res.setHeader('Content-Type', 'text/markdown');
      res.setHeader('Content-Disposition', `attachment; filename="PRISM-REPORT-${inv.id}.md"`);
      return res.send(markdownContent);
    }

// HTML entity encoding utility for SEC-002 defense
function escapeHtml(str) {
  if (str === null || str === undefined) return '';
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

    // HTML format
    res.setHeader('Content-Type', 'text/html');
    return res.send(`
      <!DOCTYPE html>
      <html>
      <head>
        <title>PRISM Report: ${escapeHtml(inv.title)}</title>
        <style>
          body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif; max-width: 900px; margin: 40px auto; padding: 0 20px; line-height: 1.6; color: #1e293b; }
          h1 { color: #0f172a; border-bottom: 2px solid #e2e8f0; padding-bottom: 12px; }
          h2 { color: #334155; margin-top: 28px; border-bottom: 1px solid #f1f5f9; padding-bottom: 6px; }
          .badge { display: inline-block; padding: 2px 8px; border-radius: 4px; font-size: 12px; font-weight: bold; background: #e0e7ff; color: #3730a3; }
          pre { background: #f8fafc; padding: 12px; border-radius: 6px; border: 1px solid #e2e8f0; overflow-x: auto; }
          blockquote { border-left: 4px solid #6366f1; margin: 0; padding-left: 16px; color: #475569; font-style: italic; }
        </style>
      </head>
      <body>
        <h1>${escapeHtml(inv.title)}</h1>
        <p><span class="badge">${escapeHtml(inv.severity)}</span> <span class="badge">${escapeHtml(inv.status)}</span> <strong>ID:</strong> ${escapeHtml(inv.id)}</p>
        <h2>Problem Statement</h2>
        <blockquote>${escapeHtml(inv.problem_statement)}</blockquote>
        <h2>Root Causes (${rootCauses.length})</h2>
        <ul>${rootCauses.map(rc => `<li><strong>${escapeHtml(rc.statement)}</strong> (Confidence: ${(Number(rc.confidence || 0) * 100).toFixed(0)}%)</li>`).join('')}</ul>
        <h2>Actionable Recommendations (${recommendations.length})</h2>
        <ul>${recommendations.map(r => `<li><strong>[${escapeHtml(r.priority)}] ${escapeHtml(r.action)}</strong>: ${escapeHtml(r.rationale)}</li>`).join('')}</ul>
      </body>
      </html>
    `);
  } catch (err) {
    res.status(500).json({ success: false, error: { code: 'INTERNAL_ERROR', message: err.message } });
  }
});

module.exports = router;
